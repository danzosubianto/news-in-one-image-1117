// font.ts - a single-stroke vector font, drawn by hand for this entry.
//
// A newspaper page lives or dies on its type, and the sandbox offers no
// font files and no libraries, so the letterforms here are data: every
// glyph is a set of pen strokes on a 10-unit cap-height grid (baseline
// y=0, x-height y=7, descenders to y=-3). The renderer in canvas.ts
// walks each stroke and stamps it at whatever size and weight the layout
// asks for, which keeps headlines and body text equally crisp.
//
// Glyph format: [advanceWidth, "x,y x,y | x,y ..."] - points joined by
// spaces are one continuous stroke; "|" lifts the pen.

export interface Glyph {
  w: number;
  strokes: number[][][]; // strokes -> points -> [x, y]
}

