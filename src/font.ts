// Decode the compact stroke strings into point arrays, once, at load.
function decode(raw: Record<string, [number, string]>): Record<string, Glyph> {
  const out: Record<string, Glyph> = {};
  for (const key of Object.keys(raw)) {
    const [w, spec] = raw[key];
    const strokes = spec.split('|').map((stroke) =>
      stroke
        .trim()
        .split(' ')
        .map((pair) => pair.split(',').map(Number)),
    );
    out[key] = { w, strokes };
  }
  return out;
}

export const GLYPHS: Record<string, Glyph> = decode(RAW);

// Characters with no letterform of their own still need an advance so
// words keep their spacing; anything unknown falls back to the space.
export const SPACE_WIDTH = 4.5;

export function glyphFor(ch: string): Glyph {
  return GLYPHS[ch] ?? { w: SPACE_WIDTH, strokes: [] };
}
